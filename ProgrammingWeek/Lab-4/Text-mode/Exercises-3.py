# 1. กำหนดค่า x เองตรงๆ (เช่น ให้ x เท่ากับ 42)
x = 42

print("=== เกมทายตัวเลข (1 - 100) ===")
print("ใส่เลข 0 หากต้องการยอมแพ้และดูเฉลย\n")

while True:
    guess = int(input("ทายตัวเลข (1-100): "))
    
    # ถ้าผู้ใช้ใส่เลข 0 ให้เลิกเล่นและเฉลย
    if guess == 0:
        print(f"คุณเลือกเลิกเล่น! เฉลยค่า x คือ: {x}")
        break
        
    # ถ้าทายถูก
    elif guess == x:
        print("ยินดีด้วย! คุณทายถูกต้องแล้ว 🎉")
        break
        
    # ถ้าเดามากกว่า x
    elif guess > x:
        print("ค่าที่คุณใส่มา 'มากกว่า' ค่าของ x")
        
    # ถ้าเดาน้อยกว่า x
    else:
        print("ค่าที่คุณใส่มา 'น้อยกว่า' ค่าของ x")