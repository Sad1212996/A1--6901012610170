"""
===================================================================
โจทย์เพิ่มเติมสำหรับ Lab 4: โปรแกรมตรวจสอบรหัสผ่าน (Password Validator)
-------------------------------------------------------------------
คำอธิบายโจทย์:
ให้เขียนโปรแกรมรับรหัสผ่านจากผู้ใช้ โดยระบบจะตรวจสอบความปลอดภัยดังนี้
1. รหัสผ่านต้องมีความยาวอย่างน้อย 8 ตัวอักษร
2. รหัสผ่านต้องไม่เป็นรหัสผ่านที่ไม่ปลอดภัย (เช่น "12345678" หรือ "password")

เงื่อนไขการทำงาน:
- หากรหัสผ่านไม่ผ่านเงื่อนไข ให้แสดงข้อความแจ้งเตือน และวนลูปรับรหัสผ่านใหม่
- หากรหัสผ่านถูกต้องตามเงื่อนไข ให้แสดงข้อความ "Password set successfully!" แล้วจบการทำงาน
- หากผู้ใช้ต้องการยกเลิก ให้พิมพ์ "exit" เพื่อออกจากโปรแกรม

จุดประสงค์หลักที่ได้ฝึกฝน:
1. การใช้ Logical Operators (and, or, not) ในการเช็คเงื่อนไขซับซ้อน
2. การใช้ Relational Operators (>=, !=, ==)
3. การควบคุมวงรอบด้วย while loop และการใช้ break
===================================================================
"""

print("=== ระบบตั้งรหัสผ่าน (Password Validator) ===")
print("เงื่อนไข: ต้องมีความยาวอย่างน้อย 8 ตัวอักษร และห้ามใช้รหัสผ่านเดาง่าย")
print("พิมพ์ 'exit' หากต้องการออกจากโปรแกรม\n")

while True:
    # รับค่ารหัสผ่านจากผู้ใช้
    password = input("กรุณาตั้งรหัสผ่านใหม่: ")

    # 1. เช็คเงื่อนไขออกจากโปรแกรม
    if password.lower() == "exit":
        print("ยกเลิกการตั้งรหัสผ่าน จบการทำงาน")
        break

    # 2. ตรวจสอบเงื่อนไขรหัสผ่าน:
    # - len(password) >= 8  : ความยาวต้องไม่น้อยกว่า 8 ตัวอักษร
    # - password != "12345678" และ password != "password" : ห้ามใช้รหัสผ่านต้องห้าม
    if len(password) >= 8 and password != "12345678" and password != "password":
        print("\n🎉 Password set successfully! (ตั้งรหัสผ่านสำเร็จ)")
        break  # เมื่อตั้งรหัสผ่านสำเร็จ ให้หลุดออกจากลูปเพื่อจบโปรแกรม
    else:
        # กรณีรหัสผ่านไม่ผ่านเงื่อนไข ให้แจ้งเตือนและวนกลับไปรับค่าใหม่
        print("❌ รหัสผ่านไม่ปลอดภัย! (ต้องยาว 8 ตัวขึ้นไป และห้ามใช้รหัสผ่านเดาง่าย) ลองใหม่อีกครั้ง\n")