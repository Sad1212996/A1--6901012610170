while True:
    # รับจำนวนเงิน (จำนวนเต็ม)
    amount = int(input("ป้อนจำนวนเงินที่ต้องการแลก (หรือ 0 เพื่อออกจากโปรแกรม): "))
    
    # ถ้าป้อน 0 ให้หยุดการทำงาน
    if amount == 0:
        break
    
    # คำนวณจำนวนเหรียญ 10 บาท
    coin10 = amount // 10
    amount %= 10
    
    # คำนวณจำนวนเหรียญ 5 บาท
    coin5 = amount // 5
    amount %= 5
    
    # จำนวนเงินที่เหลือคือจำนวนเหรียญ 1 บาท
    coin1 = amount
    
    # แสดงผลลัพธ์
    print(f"เหรียญ 10 จำนวน {coin10} เหรียญ")
    print(f"เหรียญ 5 จำนวน {coin5} เหรียญ")
    print(f"เหรียญ 1 จำนวน {coin1} เหรียญ")
    print()  # เว้นบรรทัด