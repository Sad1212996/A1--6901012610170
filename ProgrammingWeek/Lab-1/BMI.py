# Calculate Body Mass Index (BMI) from weight and height
W = int(input("Enter your weight in kilograms: "))  # รับค่าน้ำหนักเป็นกิโลกรัม (ได้เเค่จำนวนเต็ม)
H = float(input("Enter your height in meters: "))  # รับค่าความสูงเป็นเมตร 
BMI = W / (H ** 2)  # คำนวณค่า BMI (** คือ ยกกำลัง)
print(f"Your BMI is: {BMI:.2f}")  # แสดงผลลัพธ์ค่า BMI (เเสดงเเค่ทศนิยม 2 ตำแหน่ง)



