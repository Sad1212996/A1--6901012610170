# Calculate circumference and area of a circle from its diameter (not radius)

D = int(input("Enter the diameter of the circle: "))  # รับค่าเส้นผ่านศูนย์กลางของวงกลม(ได้เเค่จำนวนเต็ม)
C = 3.14 * D  # คำนวณเส้นรอบวงของวงกลม
print(f"Circumference of the circle is: {C:.2f}")  # แสดงผลลัพธ์เส้นรอบวงของวงกลม (เเสดงเเค่ทศนิยม 2 ตำแหน่ง)



