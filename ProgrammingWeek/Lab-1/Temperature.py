# Convert temperature in Celsius to Fahrenheit
C = int(input("Enter temperature in Celsius: "))  # รับค่าอุณหภูมิเป็นองศาเซลเซียส (ได้ทั้งเเค่จำนวนเต็ม)
F = (C * 9/5) + 32  # คำนวณอุณหภูมิเป็นองศาฟาเรนไฮต์
print(f"Temperature in Fahrenheit is: {F:.2f}")  # แสดงผลลัพธ์อุณหภูมิเป็นองศาฟาเรนไฮต์ (เเสดงเเค่ทศนิยม 2 ตำแหน่ง)



